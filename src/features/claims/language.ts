/**
 * What this software is not allowed to say.
 *
 * Every other safeguard in this codebase protects a fact. This one protects a
 * promise — and promises are where roofing contractors get sued, lose licences,
 * and end up in state attorney-general consent orders. A rep who overstates a
 * measurement has made a mistake. A rep who tells a homeowner "insurance will
 * pay for all of this" has made a representation the company cannot honour,
 * about money that is not the company's to commit, on behalf of a carrier that
 * has not been asked.
 *
 * The rule is narrow and absolute: nothing generated by this system — proposal
 * copy, an AI approach script, a claim summary, a text message draft — asserts
 * that a claim will be approved, that insurance will pay, or that a cost will
 * be covered. Not hedged, not "typically", not "in our experience". The check
 * runs on the finished string, after any model has written it, because the
 * point of failure is the sentence that reaches the homeowner and nothing
 * upstream of it.
 *
 * WHAT IS BANNED AND WHAT IS NOT
 *
 * This is not a ban on discussing insurance. "We will document this for your
 * carrier" is fine and is the actual product. "Your deductible is what you pay"
 * is fine. What is banned is the SPEECH ACT of guaranteeing an outcome
 * controlled by somebody else. The distinction the patterns below draw is
 * between describing a process and promising its result.
 *
 * A second, quieter category is banned too: claims of universal success
 * ("we win every claim", "we beat every competitor"). Those are not merely
 * distasteful, they are unprovable comparative advertising, and a competitor
 * can complain about them to the same regulator.
 */

export type ViolationKind =
  /** Promises a carrier will pay, approve, or cover. */
  | 'guarantees_coverage'
  /** Claims a perfect or universal record. */
  | 'guarantees_success'
  /** Tells the homeowner the deductible will be absorbed, waived or covered. */
  | 'deductible_inducement'
  /** Asserts damage or causation the evidence has not established. */
  | 'asserts_unproven_damage'
  /** Manufactures urgency to force a signature. */
  | 'false_urgency'

export interface Violation {
  readonly kind: ViolationKind
  /** The phrase as it appeared, so a person can find and fix it. */
  readonly matched: string
  /** Why this cannot be said, in one sentence. */
  readonly because: string
  /** Something true that does the same job. */
  readonly insteadSay: string
}

interface Rule {
  readonly kind: ViolationKind
  readonly pattern: RegExp
  readonly because: string
  readonly insteadSay: string
}

