export type LanguageCheck =
  | { readonly ok: true }
  | { readonly ok: false; readonly violations: readonly Violation[] }

/**
 * Check finished copy before a person sees it.
 *
 * Runs on the output string rather than on a prompt, because a model asked
 * nicely not to promise things will still do so under the right phrasing, and
 * because copy also arrives from templates, from a rep typing, and from a field
 * pasted out of somebody's old proposal.
 */
export function checkLanguage(text: string): LanguageCheck {
  const violations: Violation[] = []
  for (const rule of RULES) {
    const match = rule.pattern.exec(text)
    if (match !== null) {
      violations.push({
        kind: rule.kind,
        matched: match[0].trim(),
        because: rule.because,
        insteadSay: rule.insteadSay,
      })
    }
  }
  return violations.length === 0 ? { ok: true } : { ok: false, violations }
}

/**
 * Whether claim-related language is supportable at all yet.
 *
 * Separate from the wording check. Even impeccably hedged copy about storm
 * damage is not honest when the only imagery is four years old and the storm
 * was in March — so this gates on the evidence rather than on the phrasing, and
 * both have to pass.
 */
export interface EvidencePosture {
  readonly stormTier: 'A' | 'B' | 'C' | 'D' | 'E'
  /** Whether imagery exists that post-dates the storm. */
  readonly hasPostStormImagery: boolean
  /** Whether anybody has actually looked at the roof, remotely or in person. */
  readonly roofInspected: boolean
}

export type CopyStrength =
  /** Evidence supports discussing documented damage. */
  | 'documented'
  /** Evidence supports discussing the storm, not this roof. */
  | 'storm_only'
  /** Nothing yet supports a damage conversation. */
  | 'nothing_yet'

export function permittedCopyStrength(posture: EvidencePosture): CopyStrength {
  if (posture.stormTier === 'E') return 'nothing_yet'
  if (posture.roofInspected && posture.hasPostStormImagery) return 'documented'
  // A storm is a reason to ask for a look. It is not a finding about a roof.
  if (posture.stormTier === 'A' || posture.stormTier === 'B' || posture.stormTier === 'C') {
    return 'storm_only'
  }
  return 'nothing_yet'
}
